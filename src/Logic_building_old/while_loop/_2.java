package Logic_building_old.while_loop;

public class _2 {
    public static void main(String[] args) {
        int n = 10;
        System.out.println("Numbers from 10 to 1");
        //print numbers from 10 down to 1 in reverse order
        while(n >= 1)
        {
            System.out.println(n);
            n--;
        }
    }
}
